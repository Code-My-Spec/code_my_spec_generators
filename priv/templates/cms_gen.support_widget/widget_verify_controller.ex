defmodule <%= web_module %>.WidgetVerifyController do
  @moduledoc """
  `POST /_cms/verify/widget` — CodeMySpec asks this app to send a message
  through its own widget, so a working install is proven without waiting for
  a visitor. Generated by `mix cms_gen.support_widget`.

  Authenticated by the deploy key (`Authorization: Bearer <DEPLOY_KEY>`),
  because an unauthenticated caller could fill the project's inbox. Kept off
  `/health`: that is the proxy's liveness probe, and a CodeMySpec outage must
  not take this app out of rotation.

  Answers 200 only once CodeMySpec has stored the message; 503 when the widget
  cannot reach it.
  """

  use <%= web_module %>, :controller

  alias <%= app_module %>.CodeMySpec.Widget

  def create(conn, params) do
    case validate_deploy_key(conn) do
      :ok ->
        probe = probe(params)

        case Widget.verify("Widget check #{probe}", origin(conn)) do
          :ok ->
            json(conn, %{status: "sent", probe: probe})

          {:error, reason} ->
            conn
            |> put_status(:service_unavailable)
            |> json(%{status: "error", probe: probe, error: inspect(reason)})
        end

      {:error, :deploy_key_not_configured} ->
        conn
        |> put_status(:internal_server_error)
        |> json(%{status: "error", error: "Deploy key not configured on server"})

      {:error, _} ->
        conn
        |> put_status(:unauthorized)
        |> json(%{status: "error", error: "Invalid or missing deployment key"})
    end
  end

  defp probe(%{"probe" => probe}) when is_binary(probe) and probe != "",
    do: String.slice(probe, 0, 200)

  defp probe(_params), do: "cms-verify-#{System.unique_integer([:positive])}"

  # The address CodeMySpec reached, not `Endpoint.url/0`: the configured host
  # can differ (`localhost` in dev), and the origin has to name the site that
  # was asked.
  defp origin(conn) do
    URI.to_string(%URI{scheme: to_string(conn.scheme), host: conn.host, port: conn.port})
  end

  defp validate_deploy_key(conn) do
    with ["Bearer " <> provided] <- get_req_header(conn, "authorization"),
         {:ok, expected} <- expected_deploy_key() do
      if secure_compare(expected, provided), do: :ok, else: {:error, :unauthorized}
    else
      {:error, reason} -> {:error, reason}
      _ -> {:error, :missing_deploy_key}
    end
  end

  defp expected_deploy_key do
    case Application.get_env(:<%= app %>, :deploy_key) do
      key when is_binary(key) and key != "" -> {:ok, key}
      _ -> {:error, :deploy_key_not_configured}
    end
  end

  # Constant-time over equal lengths, so the key does not leak through timing.
  defp secure_compare(left, right) do
    byte_size(left) == byte_size(right) and Plug.Crypto.secure_compare(left, right)
  end
end
